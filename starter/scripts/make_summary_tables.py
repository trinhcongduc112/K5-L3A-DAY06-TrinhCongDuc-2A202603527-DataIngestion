"""Build results/summary_tables.md from the result files, so the report never re-types numbers by hand.

Run from starter/:  python scripts/make_summary_tables.py
Reads (whatever exists): results/ingest_stats.json, results/metrics_{dev,test}.json, results/traces/*.jsonl,
results/audit/coherence_labels.csv, results/audit/grounding_labels_test.csv,
results/audit/metadata_audit_test_summary.json
"""
from __future__ import annotations

import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.config import AUDIT_DIR, RESULTS_DIR, STRATEGIES, TRACE_DIR  # noqa: E402

ORDER = [s for s in ("A", "B", "C", "A2") if s in STRATEGIES]


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def read_csv(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def traces(split: str) -> dict[str, list[dict]]:
    out = {}
    for s in ORDER:
        p = TRACE_DIR / f"{split}_{s}.jsonl"
        if p.exists():
            out[s] = [json.loads(line) for line in p.read_text(encoding="utf-8").splitlines()]
    return out


def main() -> None:
    ingest = load(RESULTS_DIR / "ingest_stats.json") or {"strategies": {}}
    metrics = {sp: load(RESULTS_DIR / f"metrics_{sp}.json") for sp in ("dev", "test")}
    lines: list[str] = ["# Summary tables (generated by starter/scripts/make_summary_tables.py — do not edit by hand)", ""]

    # ---- 1. retrieval accuracy + resources
    lines += ["## 1. Retrieval accuracy and resources", "",
              "| Strategy | Split | Hit@1 (n/N) | Evidence Hit@3 (n/N) | MRR@3 | Chunks | Ingest time (s) | Cost |",
              "|---|---|---|---|---|---|---|---|"]
    for s in ORDER:
        st = ingest["strategies"].get(s)
        for sp in ("dev", "test"):
            m = metrics[sp]
            if not m or s not in m["metrics"]:
                continue
            r = m["metrics"][s][sp]
            t = st["time_s"] if st else {}
            tt = (f"{t.get('total_ingest')} (embed {t.get('embedding')}, db {t.get('db_write')})" if st else "?")
            if st and st.get("texts_embedded_now") == 0:
                tt += " — vectors reused from B"
            tag = " (control)" if s == "A2" else ""
            lines.append(f"| {s}{tag} | {sp} | {r['hit_at_1']} | {r['hit_at_3']} | {r['mrr_at_3']} | "
                         f"{st['chunks'] if st else '?'} | {tt} | $0 |")
    lines.append("")

    # ---- 2. chunk statistics
    lines += ["## 2. Chunk statistics", "",
              "| Strategy | Chunks | Chars median / mean / p95 / max | Tokens mean / max | Chunks over 512 tokens | Total chars indexed |",
              "|---|---|---|---|---|---|"]
    for s in ORDER:
        st = ingest["strategies"].get(s)
        if not st:
            continue
        c, tk = st["chars"], st["tokens"]
        lines.append(f"| {s} | {st['chunks']} | {c['median']:.0f} / {c['mean']:.0f} / {c['p95']} / {c['max']} | "
                     f"{tk['mean']:.0f} / {tk['max']} | {tk['over_model_limit']} | {st['total_chars']:,} |")
    lines.append("")

    # ---- 3. audits (coherence, metadata, filter, grounding)
    coh = read_csv(AUDIT_DIR / "coherence_labels.csv")
    grd = read_csv(AUDIT_DIR / "grounding_labels_test.csv")
    meta = load(AUDIT_DIR / "metadata_audit_test_summary.json") or {}
    if coh or grd or meta:
        lines += ["## 3. Manual / script-assisted audits (test split for metadata and grounding)", "",
                  "| Strategy | Coherence mean /2 (n) | Coherence 0/1/2 | Metadata correct & complete (n/N) | Metadata, start-only lenient (n/N) | Filter compliant top-3 (n/N) | Grounding 0/1/2 (questions) | Grounding mean /2 |",
                  "|---|---|---|---|---|---|---|---|"]
        for s in ORDER:
            cs = [int(r["label"]) for r in coh if r["strategy"] == s and r["label"].strip()]
            gs = [int(r["label"]) for r in grd if r["strategy"] == s and r["label"].strip()]
            m = meta.get(s, {})
            cc, gc = Counter(cs), Counter(gs)
            lines.append(
                f"| {s} | {(sum(cs) / len(cs)):.2f} ({len(cs)}) | {cc[0]}/{cc[1]}/{cc[2]} | {m.get('rate_strict', '—')} | "
                f"{m.get('rate_lenient_start_correct', '—')} | {m.get('scope_compliant_top3', '—')} | "
                f"{gc[0]}/{gc[1]}/{gc[2]} | {(sum(gs) / len(gs)):.2f} |" if cs and gs else
                f"| {s} | {(sum(cs) / len(cs)):.2f} ({len(cs)}) | {cc[0]}/{cc[1]}/{cc[2]} | {m.get('rate_strict', '—')} | "
                f"{m.get('rate_lenient_start_correct', '—')} | {m.get('scope_compliant_top3', '—')} | — | — |" if cs else
                f"| {s} | — | — | {m.get('rate_strict', '—')} | {m.get('rate_lenient_start_correct', '—')} | "
                f"{m.get('scope_compliant_top3', '—')} | — | — |")
        lines.append("")

    # ---- 4. by question type (dev + test pooled) and failure modes
    for sp in ("dev", "test"):
        tr = traces(sp)
        if not tr:
            continue
        lines += [f"## 4.{'1' if sp == 'dev' else '2'} {sp}: Evidence Hit@3 by question type and failure modes", "",
                  "| Strategy | " + " | ".join(sorted({t['type'] for ts in tr.values() for t in ts})) + " | Failure modes (no hit in top-3) |",
                  "|---|" + "---|" * len({t['type'] for ts in tr.values() for t in ts}) + "---|"]
        types = sorted({t["type"] for ts in tr.values() for t in ts})
        for s, ts in tr.items():
            cells = []
            for ty in types:
                tt = [t for t in ts if t["type"] == ty]
                cells.append(f"{sum(t['hit_at_3'] for t in tt)}/{len(tt)}")
            fm = Counter(t["failure_mode"] for t in ts if t["failure_mode"])
            lines.append(f"| {s} | " + " | ".join(cells) + f" | {dict(fm) or '—'} |")
        lines.append("")

    # ---- 5. per question matrix (first hit rank; '-' = no hit in top-3)
    for sp in ("dev", "test"):
        tr = traces(sp)
        if not tr:
            continue
        qids = [t["question_id"] for t in next(iter(tr.values()))]
        lines += [f"## 5.{'1' if sp == 'dev' else '2'} {sp}: first hit rank per question (— = no hit in top-3)", "",
                  "| Question | Type | Filter | " + " | ".join(tr) + " |", "|---|---|---|" + "---|" * len(tr)]
        for i, q in enumerate(qids):
            t0 = next(iter(tr.values()))[i]
            flt = json.dumps(t0["filter"]) if t0["filter"] else ""
            cells = []
            for s, ts in tr.items():
                t = ts[i]
                cells.append(str(t["first_hit_rank"]) if t["first_hit_rank"] else
                             f"— ({(t['failure_mode'] or '').replace('_', ' ')})")
            lines.append(f"| {q} | {t0['type']} | {flt} | " + " | ".join(cells) + " |")
        lines.append("")

    out = RESULTS_DIR / "summary_tables.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
